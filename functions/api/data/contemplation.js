            "نُسَبِّحُ بِحَمْدِكِ بُكْرَةً وَعَشِيّاً، وَنَشْهَدُ أَنْ لاَ سُلْطَانَةَ غَيْرُكِ فِي هَذَا الوُجُودِ (37) ۝",
            "وَآخِرُ دَعْوَانَا أَنْ تَظَلِّي سَيِّدَةَ العَرْشِ وَالخُلُودِ إِلَى أَبَدِ الآبِدِينَ (38) ۝",
            "نُمَجِّدُ اسْمَكِ العَظِيمَ فِي مَحَارِيبِ العِشْقِ، وَنَرْفَعُ رَايَاتِ الخُضُوعِ لِتَاجِكِ (39) ۝",
            "أَنْتِ الشَّمْسُ الَّتِي لاَ تَغْرُبُ، وَالقَمَرُ الَّذِي يُنِيرُ دُرُوبَ الصَّاغِرِينَ (40) ۝",
            "يَا رَبَّةَ الجَلاَلِ البَاقِي، لَكِ التَّسْبِيحُ مِلْءَ الأَرْضِ وَالسَّمَاوَاتِ العُلاَ (41) ۝",
            "تَتَوَارَثُ الأَجْيَالُ عُبُودِيَّتَكِ جِيلاً بَعْدَ جِيلٍ، فَلاَ تَبِيدُ وَلاَ تَنْدَثِرُ (42) ۝",
            "سُبْحَانَ مَنْ تَفَرَّدْتِ بِالحُسْنِ المُطْلَقِ، فَصِرْتِ القِبْلَةَ الَّتِي يَسْجُدُ لَهَا كُلُّ ذِي بَصَرٍ (43) ۝",
            "نُسَبِّحُ بِحَمْدِكِ بُكْرَةً وَعَشِيّاً، وَنَشْهَدُ أَنْ لاَ سُلْطَانَةَ غَيْرُكِ فِي هَذَا الوُجُودِ (44) ۝",
            "وَآخِرُ دَعْوَانَا أَنْ تَظَلِّي سَيِّدَةَ العَرْشِ وَالخُلُودِ إِلَى أَبَدِ الآبِدِينَ (45) ۝",
            "نُمَجِّدُ اسْمَكِ العَظِيمَ فِي مَحَارِيبِ العِشْقِ، وَنَرْفَعُ رَايَاتِ الخُضُوعِ لِتَاجِكِ (46) ۝",
            "أَنْتِ الشَّمْسُ الَّتِي لاَ تَغْرُبُ، وَالقَمَرُ الَّذِي يُنِيرُ دُرُوبَ الصَّاغِرِينَ (47) ۝",
